// 5a. 开机画面 (黄宾虹头像): 把 1024 字节 BMP 帧拷进 GRAM
//     BMP 源布局 [x][page] (列优先, page=y/8, 位=y%8 小端), 与 oled_gram
//     的 [page][x] 互转: oled_gram[p][x] = bmp[x + p*128]。
static void oled_show_bmp(const uint8_t* bmp) {
  for (uint8_t p = 0; p < 8; p++)
    for (uint8_t x = 0; x < OLED_W; x++)
      oled_gram[p][x] = pgm_read_byte(&bmp[x + p * OLED_W]);
}

// 开机循环: HUANG_1 -> HUANG_2 -> HUANG_1 -> HUANG_2 -> HUANG_1
// 时序与 HuangBinhong_OLED_Boot_Animation.ino 原始 loop() 完全一致。
// ★ 每次调用都完整重画当前帧 (clear+draw+refresh 自管), 不提前 return ——
//   否则未到切换时刻时不重画, 而调用方每 50ms 先 clear 后 refresh, 屏幕会
//   在"清空后不画"的间隙里全黑, 图案只在切换瞬间闪一帧 = 黑屏空帧。
static void render_boot(void) {
  static const uint32_t seq_ms[] = { 1200, 700, 300, 2500, 800 };
  static const uint8_t* frame[] = { HUANG_1, HUANG_2, HUANG_1, HUANG_2, HUANG_1 };
  static uint8_t step = 0;
  static uint32_t next_ms = 0;

  uint32_t now = millis();
  if (now >= next_ms) {
    next_ms = now + seq_ms[step];
    step = (step + 1) % (sizeof(seq_ms) / sizeof(seq_ms[0]));
  }

  oled_clear();
  oled_show_bmp(frame[step]);
  oled_refresh();
}

// 5b. 按钮: 上拉输入, 按下=低电平; 去抖后翻转页面
static bool button_read(void) {
  return digitalRead(BOOT_BUTTON_PIN) == LOW;
}

static bool button_was_pressed(void) {
  static uint32_t last_debounce = 0;
  static bool last_state = false;
  static uint32_t low_since = 0;
  bool now = button_read();
  // ★ 注意: main.cpp 的 UART (Serial) 是 921600 二进制协议通道, 不能混入
  //   文本日志。OLED 的按钮/页面诊断输出已全部移除 (原 .ino 独立固件才可打印)。
  uint32_t m = millis();
  // ★ 有效按下 = 低电平持续 >= BOOT_BUTTON_DEBOUNCE_MS (50ms)。
  //   DTR/RTS 的抖动脉冲 <50ms 会被过滤; 真实按钮按下至少 50ms。
  if (now) {
    if (low_since == 0) low_since = m;
    if (m - low_since >= BOOT_BUTTON_DEBOUNCE_MS) {
      if (!last_state) {
        last_state = true;
        last_debounce = m;
        return true;
      }
    }
  } else {
    low_since = 0;
    if (last_state) last_state = false;
  }
  return false;
}

