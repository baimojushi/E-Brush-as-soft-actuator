// oled_display.h — e-Brush ESP32-S3 机载 0.96" OLED (SSD1306 128x64, I2C) 显示层

//                    从 oled_monitor.ino 提取, 接入 main.cpp 的 Runtime rt 真实数据。

//

// 使用: 在 main.cpp 的 namespace { ... } 内部 (rt 定义之后) #include "oled_display.h";

//       setup() 里调用 oled_init();  loop() 里调用 oled_uploop();

//   OLED 走专用第二 I2C 总线 (Wire1 / I2C1), 与传感器总线 (Wire / I2C0) 物理隔离。

//   按钮: 外接按钮, 信号脚 GPIO5, 另一端接 GND (上拉输入, 按下=低电平)。

// ============================================================================

// 1. 硬件配置

// ★ 接线前务必按板子原理图核对这两个 GPIO 是否空闲。
// OLED 使用 *专用第二 I2C 总线* — Wire1 = ESP32-S3 的 I2C1 控制器, 与
// 6.667kHz 采样的传感器总线 (Wire = I2C0) 物理隔离, 避免显示刷新挤占
// 传感器采样时序导致 sched_overrun (详见 DESIGN_OLED_I2C.md §2)。
// 2026-09-23 按板子实际接线确认: SDA=GPIO15, SCL=GPIO16。
#define OLED_SDA 15
#define OLED_SCL 16
#define OLED_CLK_HZ 400000UL

// 若必须与传感器共享总线 (不推荐): 把下面 OLED_WIRE / OLED_BUS_BEGIN 两行
// 换成 Wire 并把引脚改成固件现有 I2C0 的引脚, e.g.
//     #define OLED_WIRE Wire
//     #define OLED_BUS_BEGIN() Wire.begin(48, 47, OLED_CLK_HZ)
#define OLED_WIRE Wire1
#define OLED_BUS_BEGIN() OLED_WIRE.begin(OLED_SDA, OLED_SCL, OLED_CLK_HZ)

// 显示刷新节流: 霍尔/IMU 原始采样率 6.667kHz, 人眼可读 20Hz 足够
#define OLED_REFRESH_MS 50

// 页面切换时间 (4 行显示放不下全部数据, 双页轮换)
#define OLED_PAGE_SWITCH_MS 2000

// 传感器工程常量 —— 与 host/brush_serial.py 保持同口径, OLED 读数可直接
// 与 TouchDesigner CHOP 数值对照:
//   accel ±4g 配置: 0.122 mg/LSB   -> g = raw * 0.000122
//   gyro  ±1000dps: 35.0 mdps/LSB  -> dps = raw * 0.035
//   霍尔变体: 1 -> 820 LSB/mT, 2 -> 250 LSB/mT; 0 = 未知, 显示原始码
#define ACCEL_MG_PER_LSB 0.122f
#define GYRO_MDPS_PER_LSB 35.0f
#define HALL_LSB_PER_MT 0.0f       // 0 = 显示原始码; 填入 820.0f / 250.0f 显示 mT

// ★ 按钮 (页面切换): 外接按钮, 信号脚 GPIO5, 另一端接 GND。
//   按下时 GPIO5 被拉低 → 上拉输入 + 按下=低电平。
//   GPIO5 在 brush_config.h 中未被占用 (HALL 8/9/4、SPI 12/11/13/10)。
#define BOOT_BUTTON_PIN 5
#define BOOT_BUTTON_DEBOUNCE_MS 50
// 开机稳定期: 上电瞬间 GPIO5 电平未稳定, 短暂稳定期内忽略按钮。
#define BOOT_STABLE_MS 500

// 2. 传感器数据快照 (★ 必须放在第一个函数定义之前 ★)
//    PlatformIO/Arduino 的 .ino 预处理器会把所有函数原型插到文件内首个函数
//    定义之前; 若此处自定义类型声明晚于函数, 自动生成的原型就会引用到
//    尚未声明的类型而编译失败。因此本 typedef 必须位于文件前部。
typedef struct {
  int32_t hall_x, hall_y, hall_z;   // TMAG5273 原始码 (或经变体系数换算)
  int32_t hall_temp_raw;
  int32_t accel[3];                 // 原始码
  int32_t gyro[3];                  // 原始码
  int32_t quat[4];                  // q0..q3 (Mahony 输出, 归一化后取整放大)
  uint16_t device_status;           // 契约 STATUS_BITS: bit0 hall_present, ...
  uint8_t  drop_flags;              // 契约 DROP_BITS: bit0 sched_overrun, ...
  bool     hall_ok, imu_ok, pose_ok;
} sensor_snapshot_t;

