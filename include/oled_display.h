// 6. setup / loop
static uint32_t last_refresh = 0;
// ★ 三态页面: 0=开机页(黄宾虹动画) / 1=数据页0(霍尔+加速度+陀螺)
//              / 2=数据页1(四元数+温度+运行信息)。按钮循环切换, 无自动轮换。
static uint8_t disp_state = 0;

// 开机自动探测 I2C 地址: SSD1306 默认 0x3C (0x3C<<1 = 0x78, 即例程的 0x78),
// 部分模块可通过背面跳线切到 0x3D。
static uint8_t probe_oled_addr(void) {
  static const uint8_t candidates[] = { 0x3C, 0x3D };
  for (size_t i = 0; i < sizeof(candidates); i++) {
    OLED_WIRE.beginTransmission(candidates[i]);
    if (OLED_WIRE.endTransmission() == 0) return candidates[i];
  }
  return 0x00;   // 未找到
}


void oled_uploop(void) {   // 供固件主循环调用的显示任务 (见 README 接入步骤)
  // ★ 按钮: 三态循环切换 —— 开机页 -> 数据页0 -> 数据页1 -> 开机页 -> ...
  uint32_t now = millis();
  if (now >= BOOT_STABLE_MS && button_was_pressed()) {
    disp_state = (disp_state + 1) % 3;
    last_refresh = 0;   // 立即重绘, 不等 50ms 节流
    // 诊断说明: page 切换不再打日志 (main.cpp 串口是二进制协议通道)
  }

  read_sensor_snapshot();   // 从 Runtime rt 读取真实传感器数据

  // render_*() 已自包含 clear+draw+refresh, 这里只管节流
  if (now - last_refresh >= OLED_REFRESH_MS) {
    last_refresh = now;
    if (oled_present) {
      if (disp_state == 0) {
        render_boot();        // 开机页: 黄宾虹头像动画
      } else {
        render_page(disp_state - 1);  // 数据页0/1: 霍尔 / IMU / 四元数
      }
    }
  }
}

