static uint8_t oled_addr = 0x00;         // 探测后写入
static bool oled_present = false;
// ★ GRAM 布局: [page][x] 页优先 —— oled_refresh() 用 &oled_gram[i][0]
//   取地址连续发 128 字节, SSD1306 页 i 模式下这 128 字节 = 列0..127。
//   (曾误声明为 [OLED_W][8] 列优先, &oled_gram[0][i] 往后 128 字节会跨页
//    拼接, 导致整屏画面错位 = 花屏。)
static uint8_t oled_gram[8][OLED_W];     // 页寻址: [page][x]

static void oled_wr_byte(uint8_t dat, uint8_t mode) {
  OLED_WIRE.beginTransmission(oled_addr);
  OLED_WIRE.write(mode ? 0x40 : 0x00);   // 0x00=命令流, 0x40=数据流
  OLED_WIRE.write(dat);
  OLED_WIRE.endTransmission();
}

// 数据流分块写: ESP32 Arduino 默认 I2C 缓冲 ~128B, 页刷新(128B)需分块
static void oled_wr_data(const uint8_t* p, size_t n) {
  const size_t CHUNK = 32;
  size_t off = 0;
  while (off < n) {
    size_t k = (CHUNK < (n - off)) ? CHUNK : (n - off);
    OLED_WIRE.beginTransmission(oled_addr);
    OLED_WIRE.write(0x40);
    OLED_WIRE.write(p + off, k);
    OLED_WIRE.endTransmission();
    off += k;
  }
}

static void oled_clear(void) {
  for (uint8_t p = 0; p < 8; p++)
    for (uint8_t x = 0; x < OLED_W; x++)
      oled_gram[p][x] = 0;
}

// 全屏刷新: 8 页 x 128 列 (与例程 OLED_Refresh 相同, 页寻址模式)
// ★ &oled_gram[i][0] 是页 i 的 128 列连续内存 —— 页优先布局才能这样取。
static void oled_refresh(void) {
  for (uint8_t i = 0; i < 8; i++) {
    oled_wr_byte(0xB0 + i, OLED_CMD);
    oled_wr_byte(0x00, OLED_CMD);
    oled_wr_byte(0x10, OLED_CMD);
    oled_wr_data(&oled_gram[i][0], OLED_W);
  }
}

// forward decl: probe_oled_addr 定义在后面 (提取自原 setup() 段)
static uint8_t probe_oled_addr(void);

// 初始化序列: 中景园例程命令原样 (0x20/0x02 页寻址, charge pump 0x8D/0x14)
// ★ 必须自包含探测逻辑: 原 .ino 的 setup() 里是
//     oled_addr = probe_oled_addr();
//     oled_present = (oled_addr != 0x00);
//     if (oled_present) { oled_init(); ... }
//   提取为头文件删掉 setup() 后, 探测必须并进 oled_init(), 否则 oled_present
//   恒为 false, oled_uploop() 里 if (oled_present) 永不渲染 → 全黑。
//     oled_init() 返回 true 表示成功初始化, false 表示 I2C 探测无应答。
static bool oled_init(void) {
  OLED_BUS_BEGIN();          // ★ 必须先启动 Wire1 (I2C1)
  oled_addr = probe_oled_addr();
  oled_present = (oled_addr != 0x00);
  if (!oled_present) return false;
  static const uint8_t init_cmds[] = {
    0xAE,                 // display off
    0x00, 0x10,           // column addr
    0x40,                 // start line
    0x81, 0xCF,           // contrast
    0xA1, 0xC8,           // segment remap / com scan
    0xA6,                 // normal display
    0xA8, 0x3F,           // multiplex 1/64
    0xD3, 0x00,           // display offset
    0xD5, 0x80,           // clock div
    0xD9, 0xF1,           // pre-charge
    0xDA, 0x12,           // com pins
    0xDB, 0x40,           // vcomh
    0x20, 0x02,           // page addressing mode
    0x8D, 0x14,           // charge pump on
    0xA4, 0xA6,           // resume / normal
    0xAF                  // display on
  };
  for (size_t i = 0; i < sizeof(init_cmds); i++)
    oled_wr_byte(init_cmds[i], OLED_CMD);
  oled_clear();
  oled_refresh();
  return true;
}

// 画点 / 清点 (页寻址逐列式, 与例程一致)
static void oled_draw_point(uint8_t x, uint8_t y) {
  if (x >= OLED_W || y >= OLED_H) return;
  oled_gram[y / 8][x] |= (1 << (y % 8));
}
static void oled_clear_point(uint8_t x, uint8_t y) {
  if (x >= OLED_W || y >= OLED_H) return;
  oled_gram[y / 8][x] &= ~(1 << (y % 8));
}

// 4. 文本 (复用中景园 font.h: asc2_1206 / asc2_1608 / asc2_2412)
static void oled_show_char(uint8_t x, uint8_t y, char chr, uint8_t size1) {
  uint8_t size2 = (size1 / 8 + ((size1 % 8) ? 1 : 0)) * (size1 / 2);
  uint8_t chr1 = (uint8_t)(chr - ' ');
  uint8_t y0 = y;
  for (uint8_t i = 0; i < size2; i++) {
    uint8_t temp;
    if (size1 == 12)      temp = pgm_read_byte(&asc2_1206[chr1][i]);
    else if (size1 == 16) temp = pgm_read_byte(&asc2_1608[chr1][i]);
    else if (size1 == 24) temp = pgm_read_byte(&asc2_2412[chr1][i]);
    else return;
    for (uint8_t m = 0; m < 8; m++) {
      if (temp & 0x80) oled_draw_point(x, y);
      else             oled_clear_point(x, y);
      temp <<= 1;
      y++;
      if ((y - y0) == size1) { y = y0; x++; break; }
    }
  }
}

static void oled_show_string(uint8_t x, uint8_t y, const char* s, uint8_t size1) {
  while (*s >= ' ' && *s <= '~') {
    oled_show_char(x, y, *s, size1);
    x += size1 / 2;
    if (x > OLED_W - size1 / 2) { x = 0; y += size1; }
    s++;
  }
}

